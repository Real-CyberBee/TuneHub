let currentLocale;
function normalizeLocale(value) {
  return /^zh(?:-|$)/i.test(value ?? "") ? "zh" : "en";
}

export function getLocale() {
  if (currentLocale) return currentLocale;
  let saved = null;
  try { saved = localStorage.getItem("tunehub-locale"); } catch {}
  const browserLanguages = navigator.languages?.length ? navigator.languages : [navigator.language];
  currentLocale = saved
    ? normalizeLocale(saved)
    : browserLanguages.some((value) => /^zh(?:-|$)/i.test(value ?? ""))
      ? "zh"
      : "en";
  return currentLocale;
}

export function setLocale(locale) {
  currentLocale = normalizeLocale(locale);
  try { localStorage.setItem("tunehub-locale", currentLocale); } catch {}
  return currentLocale;
}

export function toggleLocale() {
  return setLocale(getLocale() === "en" ? "zh" : "en");
}

export function t(key, values = {}) {
  const dict = messages[getLocale()];
  const parts = key.split(".");
  let value = parts.reduce((node, part) => node?.[part], dict);
  if (value == null) value = key;
  if (typeof value !== "string") return value;
  return value.replace(/\{(\w+)\}/g, (_, name) => String(values[name] ?? `{${name}}`));
}

export function localizedScene(scene) {
  const key = `baseScene${scene.id === "handpan-solo" ? "Handpan" : scene.id[0].toUpperCase() + scene.id.slice(1)}`;
  return { ...scene, ...(t(key) ?? {}) };
}

